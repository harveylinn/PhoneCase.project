function parseRows(rows: string[], chain: StoreChain): NantunStore[] {
  return rows.map((row) => {
    const [id, name, address] = row.split('|')
    const roads = ROAD_DEFINITIONS
      .filter(({ aliases }) => aliases.some((alias) => address.includes(alias)))
      .map(({ name: road }) => road)

    return {
      id,
      name,
      address,
      chain,
      county: '臺中市',
      district: '南屯區',
      roads
    }
  })
}

